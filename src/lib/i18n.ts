export type Locale = "en" | "es";

export const LOCALE_KEY = "revive-motion-locale";

export function loadDeviceLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return localStorage.getItem(LOCALE_KEY) === "es" ? "es" : "en";
}

export function saveDeviceLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  localStorage.setItem(LOCALE_KEY, locale);
}

export function clinicLocale(user?: { language?: Locale } | null): Locale {
  if (user?.language === "es" || user?.language === "en") return user.language;
  return loadDeviceLocale();
}

