export type CopyKey = keyof typeof copy.en;

export function t(key: CopyKey, locale: Locale = "en"): string {
  return copy[locale][key] ?? copy.en[key];
}

export function tf(key: CopyKey, locale: Locale, vars: Record<string, string | number>): string {
  return t(key, locale).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function headlineFromProgress(
  locale: Locale,
  input: {
    latestPeak: number | null;
    firstPeak: number | null;
    change: number | null;
    sessions: number;
    goal: number;
  }
): string {
  if (input.latestPeak != null && input.change != null && input.sessions >= 2) {
    if (input.change > 0) {
      return tf("headlineUp", locale, {
        change: input.change,
        first: input.firstPeak ?? 0,
        latest: input.latestPeak,
        goal: input.goal,
      });
    }
    if (input.change < 0) {
      return tf("headlineDown", locale, { change: Math.abs(input.change) });
    }
    return tf("headlineHold", locale, { latest: input.latestPeak });
  }
  if (input.latestPeak != null) {
    return tf("headlineFirst", locale, { latest: input.latestPeak });
  }
  return t("headlineEmpty", locale);
}

